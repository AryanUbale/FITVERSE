export const getExerciseVideo = (idOrName) => {
  if (!idOrName) return { ...exerciseVideos[0], startTime: 30 };
  const query = idOrName.toLowerCase();
  const match =
    exerciseVideos.find((v) => v.id.toLowerCase() === query) ||
    exerciseVideos.find((v) => v.name.toLowerCase() === query) ||
    exerciseVideos.find((v) => query.includes(v.id.toLowerCase()) || v.id.toLowerCase().includes(query)) ||
    exerciseVideos[0];
  return { ...match, startTime: match.startTime ?? 30 };
};

